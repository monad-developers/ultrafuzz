import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { artifactSchemaRegistry, parseStrictJsonBytes, readRegularFileSnapshot } from "@ultrafuzz/artifacts";
import { topologySchemaRegistry } from "@ultrafuzz/topology";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCodeImport from "ajv/dist/standalone/index.js";
import addFormatsImport from "ajv-formats";

const MAX_SCHEMA_BYTES = 4 * 1024 * 1024;
const DASHBOARD_HTTP_SCHEMA_ID = "urn:ultrafuzz:schema:dashboard:http:1";
const DASHBOARD_SSE_SCHEMA_ID = "urn:ultrafuzz:schema:dashboard:sse:1";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const dashboardSchemaDirectory = path.resolve(scriptDirectory, "..", "schema");
const outputDirectory = path.resolve(scriptDirectory, "..", "frontend", ".generated");
const outputPath = path.join(outputDirectory, "dashboard-wire-validators.ts");

const dashboardSchemas = [
  loadDashboardSchema("dashboard-http.schema.json", DASHBOARD_HTTP_SCHEMA_ID),
  loadDashboardSchema("dashboard-sse.schema.json", DASHBOARD_SSE_SCHEMA_ID)
];
const ajv = new Ajv2020({
  strict: true,
  allErrors: true,
  validateSchema: true,
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
  ownProperties: true,
  allowUnionTypes: false,
  unicodeRegExp: true,
  loadSchema: undefined,
  code: { source: true, esm: true, optimize: true, lines: true }
});
const addFormats = addFormatsImport;
addFormats(ajv, { mode: "full" });

const schemas = [
  ...artifactSchemaRegistry().map((entry) => ({ id: entry.id, schema: entry.schema })),
  ...topologySchemaRegistry().map((entry) => ({ id: entry.id, schema: entry.schema })),
  ...dashboardSchemas
];
const schemaIds = new Set();
for (const entry of schemas) {
  if (schemaIds.has(entry.id)) throw new Error(`duplicate frontend schema ID: ${entry.id}`);
  schemaIds.add(entry.id);
  ajv.addSchema(structuredClone(entry.schema), entry.id);
}

for (const schemaId of [DASHBOARD_HTTP_SCHEMA_ID, DASHBOARD_SSE_SCHEMA_ID]) {
  if (ajv.getSchema(schemaId) === undefined) throw new Error(`frontend schema did not compile: ${schemaId}`);
}

const standaloneCode = standaloneCodeImport;
const generated = standaloneCode(ajv, {
  validateDashboardHttpSchema: DASHBOARD_HTTP_SCHEMA_ID,
  validateDashboardSseSchema: DASHBOARD_SSE_SCHEMA_ID
});
const generatedEsm = generated
  .replace(
    /^const ([A-Za-z_$][A-Za-z0-9_$]*) = require\("([^"]+)"\)\.default;$/gmu,
    (_statement, binding, modulePath) =>
      `import ${binding}Module from "${esmModulePath(modulePath)}";\nconst ${binding} = typeof ${binding}Module === "function" ? ${binding}Module : ${binding}Module.default;`
  )
  .replace(
    /^const ([A-Za-z_$][A-Za-z0-9_$]*) = require\("([^"]+)"\)(\.[^;]+);$/gmu,
    (_statement, binding, modulePath, memberPath) =>
      `import ${binding}Module from "${esmModulePath(modulePath)}";\nconst ${binding} = ${binding}Module${memberPath};`
  );
if (/\brequire\s*\(/u.test(generatedEsm)) {
  throw new Error("frontend standalone validator contains a CommonJS runtime dependency");
}
const source = `/* eslint-disable */
// @ts-nocheck
// Generated by scripts/generate-frontend-validators.mjs from the canonical registered JSON Schemas.
// Do not edit this file directly.
${generatedEsm}
`;

fs.mkdirSync(outputDirectory, { recursive: true });
const temporaryPath = `${outputPath}.${process.pid}.tmp`;
try {
  fs.writeFileSync(temporaryPath, source, { encoding: "utf8", flag: "wx" });
  fs.renameSync(temporaryPath, outputPath);
} catch (error) {
  let cleanupError;
  try {
    fs.unlinkSync(temporaryPath);
  } catch (candidate) {
    if (!isErrno(candidate, "ENOENT")) cleanupError = candidate;
  }
  if (cleanupError !== undefined) {
    throw new AggregateError([error, cleanupError], "frontend validator generation and cleanup both failed", {
      cause: error
    });
  }
  throw error;
}

function loadDashboardSchema(filename, expectedId) {
  const snapshot = readRegularFileSnapshot(path.join(dashboardSchemaDirectory, filename), MAX_SCHEMA_BYTES);
  const schema = parseStrictJsonBytes(snapshot, {
    maxBytes: MAX_SCHEMA_BYTES,
    maxDepth: 128,
    maxItems: 200_000,
    maxProperties: 200_000
  });
  if (!isRecord(schema) || schema.$id !== expectedId) {
    throw new Error(`dashboard schema has an unexpected identity: ${filename}`);
  }
  return { id: expectedId, schema };
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isErrno(error, code) {
  return isRecord(error) && error.code === code;
}

function esmModulePath(modulePath) {
  return modulePath.endsWith(".js") ? modulePath : `${modulePath}.js`;
}

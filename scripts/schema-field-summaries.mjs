/**
 * Generate the derived field summary that output-contract prompts point agents at (#1298).
 *
 * Several pinned schemas are larger than a single agent read, so every agent that needed one
 * field spent a turn on a failed whole-file read. The summary is the shape alone - required
 * members, types, enums - with a JSON Pointer on every line that hides a branch, so the full
 * schema is queried at a known path instead of paged through. The schema stays the sole
 * authority: nothing validates against a summary.
 *
 * Checked in and verified with `--check` so reviewers see exactly what agents will read.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const schemaDirectory = path.join(root, "packages", "artifacts", "schema");
const indexPath = path.join(schemaDirectory, "field-summaries.index.json");
const SUMMARY_SUFFIX = ".summary.txt";

/**
 * Byte size at which a schema stops fitting in one agent read. Observed token density across
 * these schemas runs 2.2-4.0 bytes per token - the character-class regex guards are unusually
 * token-dense - so the threshold is set against the denser end: 50 KB is ~25,000 tokens at
 * 2 bytes per token. The four schemas #1298 reports measure 80-160 KB; the next largest
 * agent-visible schema is 48 KB.
 */
const SINGLE_READ_BYTE_LIMIT = 50_000;
/** Depth past which members are summarized by pointer instead of expanded. */
const MAX_DEPTH = 3;
/** Longest inline enum rendering before it collapses to a count and a pointer. */
const MAX_INLINE_ENUM_CHARS = 160;
/**
 * Total pattern characters on one member past which the summary reports it as guarded rather
 * than silently dropping the constraint. An ordinary identifier pattern in these schemas is ~35
 * characters; the expanded case-insensitive guards on report-bound free text total ~44,000.
 */
const GUARD_PATTERN_CHARS = 512;
/** Root-union variants expanded inline before the rest are left to a pointer. */
const MAX_EXPANDED_BRANCHES = 32;
const MAX_SUMMARY_LINES = 2_000;

const schemaFilenames = readdirSync(schemaDirectory)
  .filter((filename) => filename.endsWith(".schema.json"))
  .sort();
if (schemaFilenames.length === 0) throw new Error(`no schemas found in ${relative(schemaDirectory)}`);

const documents = schemaFilenames.map((filename) => {
  const schemaPath = path.join(schemaDirectory, filename);
  const bytes = readFileSync(schemaPath);
  let schema;
  try {
    schema = JSON.parse(bytes.toString("utf8"));
  } catch (error) {
    throw new Error(`${relative(schemaPath)} is not valid JSON`, { cause: error });
  }
  if (!isRecord(schema)) throw new Error(`${relative(schemaPath)} must be a JSON object`);
  return { filename, bytes, schema };
});

/**
 * Every bundled document by `$id`. A thin wrapper such as `findings.schema.json` is only an array
 * of `urn:...:finding:2`, so a summary that stopped at the document boundary would send the agent
 * straight back to the 80 KB file this change exists to avoid reading.
 */
const documentsById = new Map();
for (const document of documents) {
  const id = document.schema.$id;
  if (typeof id !== "string" || id.length === 0) {
    throw new Error(`${document.filename} has no $id to resolve cross-document references against`);
  }
  if (documentsById.has(id)) throw new Error(`two schemas declare $id ${id}`);
  documentsById.set(id, document);
}

const generated = documents.map(({ filename, bytes, schema }) => {
  const summary = renderSummary(filename, schema, bytes);
  return {
    filename,
    summaryFilename: `${filename.replace(/\.schema\.json$/u, "")}${SUMMARY_SUFFIX}`,
    schemaBytes: bytes.byteLength,
    summaryBytes: Buffer.byteLength(summary, "utf8"),
    exceedsSingleRead: bytes.byteLength >= SINGLE_READ_BYTE_LIMIT,
    summary
  };
});

const index = {
  comment:
    "Generated by scripts/schema-field-summaries.mjs; run `pnpm docs:schema-summaries`. A summary is a derived agent-facing view of a schema's shape, never a validation input.",
  single_read_byte_limit: SINGLE_READ_BYTE_LIMIT,
  summaries: Object.fromEntries(
    generated.map((entry) => [
      entry.filename,
      {
        summary_filename: entry.summaryFilename,
        schema_bytes: entry.schemaBytes,
        summary_bytes: entry.summaryBytes,
        exceeds_single_read: entry.exceedsSingleRead
      }
    ])
  )
};
const indexText = `${JSON.stringify(index, undefined, 2)}\n`;
const expectedSummaryNames = new Set(generated.map((entry) => entry.summaryFilename));
const orphanedSummaries = readdirSync(schemaDirectory)
  .filter((filename) => filename.endsWith(SUMMARY_SUFFIX) && !expectedSummaryNames.has(filename))
  .map((filename) => relative(path.join(schemaDirectory, filename)));

if (process.argv.includes("--check")) {
  const stale = [...orphanedSummaries.map((entry) => `${entry} (orphaned)`)];
  for (const entry of generated) {
    const summaryPath = path.join(schemaDirectory, entry.summaryFilename);
    if (!existsSync(summaryPath) || readFileSync(summaryPath, "utf8") !== entry.summary) {
      stale.push(relative(summaryPath));
    }
  }
  if (!existsSync(indexPath) || readFileSync(indexPath, "utf8") !== indexText) stale.push(relative(indexPath));
  if (stale.length > 0) {
    process.stderr.write(
      `schema field summaries are stale; run pnpm docs:schema-summaries\n${stale
        .map((entry) => `  ${entry}`)
        .join("\n")}\n`
    );
    process.exit(1);
  }
} else {
  if (orphanedSummaries.length > 0) {
    throw new Error(`summaries exist for removed schemas; delete them: ${orphanedSummaries.join(", ")}`);
  }
  for (const entry of generated) {
    writeFileSync(path.join(schemaDirectory, entry.summaryFilename), entry.summary, "utf8");
  }
  writeFileSync(indexPath, indexText, "utf8");
  process.stdout.write(`${generated.length} field summaries + ${relative(indexPath)}\n`);
}

function renderSummary(filename, schema, bytes) {
  const digest = crypto.createHash("sha256").update(bytes).digest("hex");
  const lines = renderDocument(schema, filename);
  if (lines.length > MAX_SUMMARY_LINES) {
    throw new Error(`${filename} summary exceeds ${MAX_SUMMARY_LINES} lines; raise the cap deliberately`);
  }
  const header = [
    `# ${filename} - derived field summary`,
    "# Shape only. The pinned schema is the sole authority on JSON shape; nothing validates against this file.",
    `# schema: ${bytes.byteLength} bytes, sha256 ${digest.slice(0, 16)}`,
    '# "*" marks a required member. "->" names the JSON Pointer to read for the detail omitted here,',
    "# prefixed with a schema filename when the detail lives in another document of the same bundle.",
    '# "(rules)" counts constraints that bind several members at once and are not shown member by member.'
  ];
  return `${[...header, ...lines].join("\n")}\n`;
}

/** Every member line for one schema document, root shape first. */
function renderDocument(schema, filename) {
  const lines = [];
  const root = resolveRef(schema, { document: schema, pointer: "", file: undefined }) ?? {
    schema,
    document: schema,
    pointer: "",
    file: undefined
  };
  const branches = rootBranches(root);
  if (isRecord(root.schema.properties)) {
    renderMembers(root, 0, lines);
  } else if (root.schema.items !== undefined) {
    const items = resolveRef(root.schema.items, childRef(root, "/items"));
    // The entry shape is expanded below, so a pointer here would name the whole referenced
    // document - for the findings wrapper, the 80 KB file this summary stands in for. The member
    // lines carry that filename wherever they do omit something.
    const expanded = items !== undefined && isRecord(items.schema.properties);
    lines.push(memberLine(0, " ", "(root)", describe(root.schema, root), expanded ? undefined : items));
    if (items !== undefined) renderMembers(items, 0, lines);
  } else if (branches !== undefined) {
    // A root union, such as event-record's 27 variants, is the whole document: a line naming the
    // branch count would send the agent back to the file this summary stands in for.
    lines.push(memberLine(0, " ", "(root)", describe(root.schema, root), childRef(root, `/${branches.key}`)));
    renderBranches(root, branches, lines);
  } else if (Array.isArray(root.schema.allOf)) {
    // Every branch of a root conjunction holds, so its members read as one object.
    let unexpanded = 0;
    for (const [index, branch] of root.schema.allOf.entries()) {
      const ref = resolveRef(branch, childRef(root, `/allOf/${index}`));
      if (ref === undefined) continue;
      if (isRecord(ref.schema.properties)) renderMembers(ref, 0, lines);
      else unexpanded += 1;
    }
    if (unexpanded > 0 && lines.length > 0) {
      lines.unshift(rulesLine(0, { count: unexpanded, pointer: childRef(root, "/allOf") }));
    }

    if (lines.length === 0) {
      lines.push(memberLine(0, " ", "(root)", describe(root.schema, root), childRef(root, "/allOf")));
    }
  } else {
    lines.push(memberLine(0, " ", "(root)", describe(root.schema, root), detailPointer(root)));
  }
  if (lines.length === 0) throw new Error(`${filename} produced no summary lines`);
  return lines;
}

/** The `oneOf`/`anyOf` variants a document is entirely made of, if any. */
function rootBranches(ref) {
  if (isRecord(ref.schema.properties)) return undefined;
  for (const key of ["oneOf", "anyOf"]) {
    if (Array.isArray(ref.schema[key]) && ref.schema[key].length > 0) return { key, items: ref.schema[key] };
  }
  return undefined;
}

function renderBranches(root, branches, lines) {
  const shown = branches.items.slice(0, MAX_EXPANDED_BRANCHES);
  const resolved = shown.map((branch, index) => resolveRef(branch, childRef(root, `/${branches.key}/${index}`)));
  const discriminator = branchDiscriminator(resolved);
  for (const [index, ref] of resolved.entries()) {
    if (ref === undefined) continue;
    const expandable = isRecord(ref.schema.properties);
    lines.push(
      memberLine(
        1,
        " ",
        `[${index}]${branchLabel(ref, discriminator)}`,
        describe(ref.schema, ref),
        expandable ? undefined : detailPointer(ref)
      )
    );
    if (expandable) renderMembers(ref, 2, lines);
  }
  if (branches.items.length > shown.length) {
    lines.push(
      memberLine(
        1,
        " ",
        `[${shown.length}..${branches.items.length - 1}]`,
        "not expanded",
        childRef(root, `/${branches.key}`)
      )
    );
  }
}

/**
 * The member that actually tells one branch from another: a fixed value that differs across the
 * union. Without this test the label would read `schema_version=...`, which every branch shares.
 */
function branchDiscriminator(refs) {
  const valuesByName = new Map();
  for (const ref of refs) {
    for (const [name, value] of branchConstants(ref)) {
      const values = valuesByName.get(name) ?? new Set();
      values.add(value);
      valuesByName.set(name, values);
    }
  }
  for (const [name, values] of valuesByName) {
    if (values.size > 1) return name;
  }
  return undefined;
}

/** A branch's fixed member values, by member name. */
function branchConstants(ref) {
  if (ref === undefined || !isRecord(ref.schema.properties)) return [];
  return Object.entries(ref.schema.properties).flatMap(([name, member]) => {
    if (!isRecord(member)) return [];
    if (member.const !== undefined) return [[name, String(member.const)]];
    if (Array.isArray(member.enum) && member.enum.length === 1) return [[name, String(member.enum[0])]];
    return [];
  });
}

/** A branch's discriminating constant, so a union reads as a tagged set rather than an index list. */
function branchLabel(ref, discriminator) {
  const constants = new Map(branchConstants(ref));
  if (discriminator !== undefined && constants.has(discriminator)) {
    return ` ${discriminator}=${constants.get(discriminator)}`;
  }
  const first = [...constants][0];
  return first === undefined ? "" : ` ${first[0]}=${first[1]}`;
}

function renderMembers(ref, depth, lines) {
  const properties = isRecord(ref.schema.properties) ? ref.schema.properties : undefined;
  if (properties === undefined) return;
  for (const rules of crossMemberRules(ref)) lines.push(rulesLine(depth, rules));
  const required = new Set(
    Array.isArray(ref.schema.required) ? ref.schema.required.filter((name) => typeof name === "string") : []
  );
  for (const name of Object.keys(properties)) {
    const member = resolveRef(properties[name], childRef(ref, `/properties/${escapePointer(name)}`));
    if (member === undefined) continue;
    const expandable = depth < MAX_DEPTH ? nestedObject(member) : undefined;
    lines.push(
      memberLine(
        depth,
        required.has(name) ? "*" : " ",
        name,
        describe(member.schema, member),
        expandable === undefined ? detailPointer(member) : undefined
      )
    );
    if (expandable !== undefined) renderMembers(expandable, depth + 1, lines);
  }
}

function memberLine(depth, marker, name, text, detail) {
  const pointer = detail === undefined ? "" : `  -> ${pointerText(detail)}`;
  return `${" ".repeat(depth * 2)}${marker}${name}: ${text}${pointer}`;
}

/** The object whose members should be expanded under a member line, if any. */
function nestedObject(ref) {
  if (isRecord(ref.schema.properties)) return ref;
  if (ref.schema.items !== undefined) {
    const items = resolveRef(ref.schema.items, childRef(ref, "/items"));
    if (items !== undefined && isRecord(items.schema.properties)) return items;
  }
  return undefined;
}

/** A compact type description. Detail that cannot fit is reported by {@link detailPointer}. */
function describe(schema, ref) {
  if (!isRecord(schema)) return "?";
  if (schema.const !== undefined) return `const(${String(schema.const)})`;
  if (Array.isArray(schema.enum)) return describeEnum(schema);
  // A union of plain scalars is shorter written out than behind a branch count and a pointer.
  const scalars = scalarUnion(schema, ref);
  if (scalars !== undefined) return scalars;
  for (const branch of ["anyOf", "oneOf"]) {
    if (Array.isArray(schema[branch])) return `${branch}[${schema[branch].length}]`;
  }
  if (isArrayLike(schema)) return describeArray(schema, ref);
  const guard = patternCharacters(schema) > GUARD_PATTERN_CHARS ? " (pattern-guarded)" : "";
  if (schema.type === "object" || isRecord(schema.properties)) return describeObject(schema, ref, guard);
  if (typeof schema.type === "string") return `${schema.type}${guard}`;
  if (Array.isArray(schema.type)) return `${schema.type.join("|")}${guard}`;
  if (Array.isArray(schema.allOf)) return `allOf[${schema.allOf.length}]${guard}`;
  return `?${guard}`;
}

function describeEnum(schema) {
  const inline = schema.enum.map((value) => String(value)).join("|");
  return inline.length <= MAX_INLINE_ENUM_CHARS ? `enum(${inline})` : `enum[${schema.enum.length} values]`;
}

function describeArray(schema, ref) {
  // `items: false` admits nothing, so the member is an array that must stay empty.
  if (schema.items === false) return "array (must be empty)";
  // A tuple's positions are its shape, so they belong inline rather than behind a pointer.
  if (Array.isArray(schema.prefixItems)) {
    return `tuple[${schema.prefixItems
      .map((item, index) => describe(item, childRef(ref, `/prefixItems/${index}`)))
      .join(", ")}]`;
  }
  const items = schema.items === undefined ? undefined : resolveRef(schema.items, childRef(ref, "/items"));
  return `array<${items === undefined ? "?" : describe(items.schema, items)}>`;
}

function describeObject(schema, ref, guard) {
  // An open map declares no members, so its value shape is the only shape it has: goal-plan's
  // `replacements` reads as `object` without it, hiding that a value must be a scalar.
  const values = mapValues(schema, ref);
  if (values !== undefined) return `object<${describe(values.schema, values)}>${guard}`;
  if (!isRecord(schema.properties) && schema.additionalProperties === false) return "object (must be empty)";
  return "object";
}

function isArrayLike(schema) {
  return schema.type === "array" || schema.items !== undefined || Array.isArray(schema.prefixItems);
}

/** The reference to read when a member's description omits something an author would need. */
function detailPointer(ref) {
  const { schema } = ref;
  if (Array.isArray(schema.enum)) {
    const inline = schema.enum.map((value) => String(value)).join("|");
    return inline.length <= MAX_INLINE_ENUM_CHARS ? undefined : childRef(ref, "/enum");
  }
  if (scalarUnion(schema, ref) !== undefined) return undefined;
  const combinator = ["anyOf", "oneOf", "allOf"].find((key) => Array.isArray(schema[key]));
  const values = mapValues(schema, ref);
  if (combinator !== undefined) {
    // A member can hide a rule set and the shape of its entries at once. Naming the combinator
    // alone sent a reader of analysis-bundle's `files` to count rules and away from the six item
    // shapes the same line advertises, so name the member and let one read cover both.
    return isArrayLike(schema) || values !== undefined ? ref : childRef(ref, `/${combinator}`);
  }
  if (isArrayLike(schema)) return itemsDetailPointer(ref);
  if (values !== undefined) return nestedDetailPointer(values);
  if (patternCharacters(schema) > GUARD_PATTERN_CHARS) return ref;
  if (isRecord(schema.properties)) return ref;
  return undefined;
}

function itemsDetailPointer(ref) {
  const { schema } = ref;
  if (Array.isArray(schema.prefixItems)) return undefined;
  if (schema.items === undefined || schema.items === false) return undefined;
  const items = resolveRef(schema.items, childRef(ref, "/items"));
  return items === undefined ? undefined : nestedDetailPointer(items);
}

/** What to read for a shape reached through array items or an open map's values. */
function nestedDetailPointer(ref) {
  return detailPointer(ref) ?? (isRecord(ref.schema.properties) ? ref : undefined);
}

/**
 * Constraints that bind several members at once - a conjunction, a conditional, a dependency -
 * which member expansion never shows. generated-tests requires a nonempty `generated_tests`
 * whenever `support_files` is nonempty, and a reader told to query named pointers has no other
 * way to reach that rule.
 */
function crossMemberRules(ref) {
  const { schema } = ref;
  const found = [];
  for (const key of ["allOf", "oneOf", "anyOf"]) {
    if (Array.isArray(schema[key]) && schema[key].length > 0) found.push({ key, count: schema[key].length });
  }
  for (const key of ["dependentRequired", "dependentSchemas"]) {
    if (isRecord(schema[key])) found.push({ key, count: Object.keys(schema[key]).length });
  }
  if (isRecord(schema.if)) found.push({ key: "if", count: 1 });
  // One line per keyword, each naming its own pointer: a single line covering two keywords could
  // only point at the member itself, which for a document root is the whole file this summary
  // exists to keep out of a read.
  return found.map((entry) => ({ count: entry.count, pointer: childRef(ref, `/${entry.key}`) }));
}

function rulesLine(depth, rules) {
  const text = `${rules.count} cross-member ${rules.count === 1 ? "rule" : "rules"}`;
  return memberLine(depth, " ", "(rules)", text, rules.pointer);
}

/**
 * The value shape of an open map: an object that declares no members of its own but constrains
 * whatever members appear. Without it such a member summarizes to a bare `object`.
 */
function mapValues(schema, ref) {
  if (!isRecord(schema) || isRecord(schema.properties)) return undefined;
  if (isRecord(schema.additionalProperties)) {
    return resolveRef(schema.additionalProperties, childRef(ref, "/additionalProperties"));
  }
  if (isRecord(schema.patternProperties)) {
    const patterns = Object.keys(schema.patternProperties);
    if (patterns.length === 1 && isRecord(schema.patternProperties[patterns[0]])) {
      return resolveRef(
        schema.patternProperties[patterns[0]],
        childRef(ref, `/patternProperties/${escapePointer(patterns[0])}`)
      );
    }
  }
  return undefined;
}

/** A union of nothing but plain scalars, written out, or undefined when a branch holds structure. */
function scalarUnion(schema, ref) {
  for (const key of ["anyOf", "oneOf"]) {
    const branches = schema[key];
    if (!Array.isArray(branches) || branches.length === 0) continue;
    const types = [];
    for (const [index, branch] of branches.entries()) {
      const resolved = resolveRef(branch, childRef(ref, `/${key}/${index}`));
      if (resolved === undefined) return undefined;
      const inner = resolved.schema;
      if (!isRecord(inner) || typeof inner.type !== "string") return undefined;
      if (!["string", "number", "integer", "boolean", "null"].includes(inner.type)) return undefined;
      if (inner.enum !== undefined || inner.const !== undefined) return undefined;
      if (patternCharacters(inner) > 0) return undefined;
      if (!types.includes(inner.type)) types.push(inner.type);
    }
    return types.join("|");
  }
  return undefined;
}

/** Total characters of `pattern` constraints reachable from a member, including through guards. */
function patternCharacters(schema, depth = 0) {
  if (depth > 6 || !isRecord(schema)) return 0;
  let total = typeof schema.pattern === "string" ? schema.pattern.length : 0;
  for (const key of ["allOf", "anyOf", "oneOf"]) {
    if (Array.isArray(schema[key])) {
      for (const branch of schema[key]) total += patternCharacters(branch, depth + 1);
    }
  }
  if (isRecord(schema.not)) total += patternCharacters(schema.not, depth + 1);
  return total;
}

/**
 * Follow `$ref` to its target, keeping the document and pointer an agent should read. A local
 * `#/...` reference stays in the current document; a `urn:` reference crosses to the bundled
 * document declaring that `$id`, and the resulting pointer carries that filename.
 */
function resolveRef(node, parent, seen = new Set()) {
  if (!isRecord(node)) return undefined;
  const reference = node.$ref;
  if (typeof reference !== "string") return { ...parent, schema: node };
  if (seen.has(reference)) return { ...parent, schema: node };
  seen.add(reference);
  if (reference.startsWith("#/")) {
    const segments = reference.slice(2).split("/").map(unescapePointer);
    let target = parent.document;
    for (const segment of segments) {
      if (!isRecord(target) || !(segment in target)) return { ...parent, schema: node };
      target = target[segment];
    }
    return resolveRef(target, { ...parent, pointer: `/${segments.map(escapePointer).join("/")}` }, seen);
  }
  const crossed = documentsById.get(reference);
  if (crossed === undefined) return { ...parent, schema: node };
  return resolveRef(crossed.schema, { document: crossed.schema, pointer: "", file: crossed.filename }, seen);
}

/** A pointer inside an already-resolved reference's own document; the caller resolves the node. */
function childRef(ref, suffix) {
  return { document: ref.document, file: ref.file, pointer: `${ref.pointer}${suffix}` };
}

function pointerText(ref) {
  return `${ref.file ?? ""}$${ref.pointer}`;
}

function escapePointer(segment) {
  return String(segment).replaceAll("~", "~0").replaceAll("/", "~1");
}

function unescapePointer(segment) {
  return segment.replaceAll("~1", "/").replaceAll("~0", "~");
}

function relative(absolutePath) {
  return path.relative(root, absolutePath).split(path.sep).join("/");
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
